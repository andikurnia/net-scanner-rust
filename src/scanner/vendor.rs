/// Look up a vendor name for a MAC address's OUI (first 3 octets).
pub fn vendor_for_mac(mac: &pnet::util::MacAddr) -> Option<&'static str> {
    let s = mac.to_string();
    if s.len() < 8 {
        return None;
    }
    let key = s[..8].to_lowercase();
    OUIS
        .iter()
        .find(|(oui, _)| *oui == key)
        .map(|(_, vendor)| *vendor)
}
